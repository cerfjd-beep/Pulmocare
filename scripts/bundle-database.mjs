import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join } from "node:path";

const directory = "supabase/migrations";
const files = (await readdir(directory)).filter((file) => /^\d{14}_.+\.sql$/.test(file)).sort();
const sections = [];
for (const file of files) {
  const sql = await readFile(join(directory, file), "utf8");
  const [version] = file.split("_");
  const name = file.slice(15, -4);
  const digest = createHash("sha256").update(sql).digest("hex");
  // Filenames are constrained above; name contains no quotes in this repository.
  if (!/^[a-z0-9_]+$/.test(name)) throw new Error("Invalid migration filename");
  sections.push(
    `-- ${file}\n-- SHA256 ${digest}\n${sql}\n` +
      `INSERT INTO supabase_migrations.schema_migrations(version, name, statements)\n` +
      `VALUES ('${version}', '${name}', ARRAY[$migration_source$${sql}$migration_source$]);\n`,
  );
}
const output = `-- Pulmocare: initial database installation, generated by npm run db:bundle.
-- Target project: dnxwecpzjobtnclyywkz. Run as postgres in Supabase SQL Editor.
-- All-or-nothing transaction. Existing Pulmocare objects cause a safe failure.
-- No DROP, no patient records, no credentials and no automatic administrative role grant.
BEGIN;
SELECT pg_advisory_xact_lock(11092026);
DO $preflight$
BEGIN
  IF to_regclass('public.profiles') IS NOT NULL
    OR to_regclass('public.service_requests') IS NOT NULL
    OR EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'private')
    OR EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pulmocare_executor') THEN
    RAISE EXCEPTION 'Existing application objects: inspect database before migrating';
  END IF;
  IF to_regclass('auth.users') IS NULL OR to_regclass('storage.buckets') IS NULL THEN
    RAISE EXCEPTION 'This installation requires Supabase Auth and Storage';
  END IF;
END;
$preflight$;
CREATE SCHEMA IF NOT EXISTS supabase_migrations;
CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations (
  version text PRIMARY KEY, statements text[], name text
);
REVOKE ALL ON SCHEMA supabase_migrations FROM PUBLIC, anon, authenticated;
REVOKE ALL ON supabase_migrations.schema_migrations FROM PUBLIC, anon, authenticated;
${sections.join("\n")}
COMMIT;
SELECT 'Pulmocare database installed' AS result,
  (SELECT count(*) FROM pg_tables WHERE schemaname='public' AND rowsecurity) AS protected_tables;
`;
await mkdir("supabase/install", { recursive: true });
await writeFile("supabase/install/pulmocare-inicial.sql", output, "utf8");
console.log(`Bundled ${files.length} migrations into supabase/install/pulmocare-inicial.sql`);
